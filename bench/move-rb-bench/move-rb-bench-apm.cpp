/**
 * @brief measures sassy on the first cfg.sassy_patterns patterns of every locate-edit pattern file (sassy
 *        supports only locate queries under the edit distance); each query scans the whole text in chunks
 *        (see sassy_capi.hpp). The RESULT lines have index_mem = 0, time_locate is the wall time of the
 *        queries and time_search the part of it spent in sassy (i.e., without reading the text)
 */
void measure_sassy(const bench_config_t& cfg)
{
    sassy_library library;
    if (!library.open(executable_dir())) return;

    if (cfg.metric == "hamming") {
        std::cerr << "note: sassy does not support the hamming distance; skipping it under --metric hamming" << std::endl;
        return;
    }

    g_index_mem = 0;

    for (const std::string& profile : cfg.sassy_profiles) {
        for (const bench_job_t& job : cfg.jobs) {
            if (job.op != OP_LOCATE || job.metric != EDIT_DISTANCE) continue;

            std::vector<std::string> patterns;
            uint64_t m;
            if (!read_pattern_file(job.path, cfg.max_patterns, patterns, m)) continue;
            if (patterns.size() > cfg.sassy_patterns) patterns.resize(cfg.sassy_patterns);
            const uint64_t num_patterns = patterns.size();

            // pass 0: plain locate, pass 1: locate with a CIGAR per occurrence (--cigar)
            for (uint8_t pass = 0; pass < 2; pass++) {
                const bool trace = pass == 1;
                if (!trace && !cfg.locate_plain()) continue;
                if (trace && !cfg.locate_cigar()) continue;

                std::cerr << "measuring sassy (" << profile << (trace ? ", CIGAR" : "") << ") on " << job.path
                          << " (" << num_patterns << " pattern(s)) ..." << std::endl;

                sassy_scanner scanner(library, cfg.sassy_text_path, profile, trace, cfg.sassy_all, cfg.sassy_chunk);
                uint64_t occurrences = 0, time_locate = 0, time_search = 0, peak_bytes = 0;
                const uint64_t mem_baseline = malloc_count_current();
                malloc_count_reset_peak();

                for (uint64_t i = 0; i < num_patterns; i++) {
                    auto t1 = now();
                    occurrences += scanner.scan(patterns[i], (uint64_t) job.k, time_search, peak_bytes);
                    time_locate += time_diff_ns(t1);
                }

                mem_stats_t mem;
                mem.peak_mem = malloc_count_peak() - mem_baseline;
                mem.occ_mem = peak_bytes;
                print_result("locate_sassy_" + profile, cfg.text_name, scanner.input_size(), "edit",
                    cfg.sassy_all ? "all" : "minima", m, num_patterns, job.k, occurrences,
                    "time_locate", time_locate, trace, mem, "time_search", time_search);
            }
        }
    }
}

